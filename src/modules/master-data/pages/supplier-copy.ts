export function useSupplierCopy() {
  const language = useLanguageStore((state) => state.language);
  return {
    copy: language === "vi" ? vi : language === "zh" ? zh : en,
    locale: language === "vi" ? "vi-VN" : language === "zh" ? "zh-CN" : "en-GB",
  };
}
