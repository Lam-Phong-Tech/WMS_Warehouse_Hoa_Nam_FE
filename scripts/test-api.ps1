$ErrorActionPreference = "Stop"
if (-not $env:QA_ADMIN_PASSWORD) { throw "Set QA_ADMIN_PASSWORD env var" }
if (-not $env:API_BASE_URL) { throw "Set API_BASE_URL env var (e.g. https://example.com/api/v1)" }
$baseUrl = $env:API_BASE_URL
$stamp = Get-Date -Format "yyyyMMdd_HHmmss"

Write-Host "=== TEST: Login admin ===" -ForegroundColor Cyan
$login = Invoke-RestMethod -Uri "$baseUrl/auth/login" -Method Post -Body (@{ email = $env:QA_ADMIN_EMAIL; password = $env:QA_ADMIN_PASSWORD } | ConvertTo-Json) -ContentType "application/json"
$token = $login.data.access_token
$authHeaders = @{ Authorization = "Bearer $token" }

if (-not $token) { throw "Login FAILED" }
Write-Host "Token OK" -ForegroundColor Green

Write-Host "`n=== Create test data ===" -ForegroundColor Cyan
$dept = Invoke-RestMethod -Uri "$baseUrl/departments" -Method Post -Headers $authHeaders -ContentType "application/json" -Body (@{
    org_unit_id = 5; code = "E2E-$stamp"; name = "E2E Test Department at $stamp";
    department_type = "phong_ban"
} | ConvertTo-Json)
$deptId = $dept.data.id
Write-Host "Created department: $deptId" -ForegroundColor Green

$task = Invoke-RestMethod -Uri "$baseUrl/tasks" -Method Post -Headers $authHeaders -ContentType "application/json" -Body (@{
    type = "task"; title = "E2E Test at $stamp"; description = "Auto-generated by test-api.ps1";
    priority = "P1"; assignee_dept_id = $deptId; due_date = (Get-Date).AddDays(7).ToString("yyyy-MM-dd HH:mm:ss")
} | ConvertTo-Json)
$taskId = $task.data.id
Write-Host "Created task: $taskId" -ForegroundColor Green

Write-Host "`n=== GET /departments/$deptId ===" -ForegroundColor Cyan
$detail = Invoke-RestMethod -Uri "$baseUrl/departments/$deptId" -Method Get -Headers $authHeaders
Write-Host "Department detail OK, name=$($detail.data.name)" -ForegroundColor Green

Write-Host "`n=== GET /tasks/$taskId ===" -ForegroundColor Cyan
$taskDetail = Invoke-RestMethod -Uri "$baseUrl/tasks/$taskId" -Method Get -Headers $authHeaders
Write-Host "Task detail OK, title=$($taskDetail.data.title)" -ForegroundColor Green

Write-Host "`n=== GET /departments ===" -ForegroundColor Cyan
$list = Invoke-RestMethod -Uri "$baseUrl/departments?page=1&per_page=5" -Method Get -Headers $authHeaders
Write-Host "Department list: $($list.data.Count) items" -ForegroundColor Green

Write-Host "`n=== GET /tasks ===" -ForegroundColor Cyan
$taskList = Invoke-RestMethod -Uri "$baseUrl/tasks?page=1&per_page=5" -Method Get -Headers $authHeaders
Write-Host "Task list: $($taskList.data.Count) items" -ForegroundColor Green

Write-Host "`n=== Cleanup: soft-delete department ===" -ForegroundColor Cyan
try { Invoke-RestMethod -Uri "$baseUrl/departments/$deptId/force-delete" -Method Delete -Headers $authHeaders -ErrorAction SilentlyContinue | Out-Null } catch {}

Write-Host "`n=== ALL TESTS PASSED ===" -ForegroundColor Green